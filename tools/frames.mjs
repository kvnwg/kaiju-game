// Draws the UI's pixel frames from ASCII art and writes them into styles.css, between the
// "frames:begin" and "frames:end" comments, as CSS variables of SVG data URIs. Each frame is a
// 9-slice ring (border-image, 4 frame pixels from each side) laid over the element's own
// background: an opaque dark outline with rounded, stepped corners, a soft highlight along the
// top and a shade along the bottom. The inside is see-through, so one frame suits any colour.
// Usage: node tools/frames.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// ' ' outside (clipped off), '_' inside (the element's background shows), O outline,
// H highlight, S shade.
const FRAMES = {
  // Pills, panels and cards.
  frame: [
    '  OOOOOO  ',
    ' OHHHHHHO ',
    'OH______HO',
    'O________O',
    'O________O',
    'O________O',
    'O________O',
    'OS______SO',
    ' OSSSSSSO ',
    '  OOOOOO  ',
  ],
  // Buttons: a deeper shade and a thicker base, so they sit up off the page.
  'frame-btn': [
    '  OOOOOO  ',
    ' OHHHHHHO ',
    'OH______HO',
    'O________O',
    'O________O',
    'O________O',
    'OS______SO',
    'OSSSSSSSSO',
    ' OOOOOOOO ',
    '  OOOOOO  ',
  ],
};
const COLORS = { O: '#2a1736', H: 'rgba(255,255,255,0.42)', S: 'rgba(42,23,54,0.22)' };

function svg(rows) {
  const w = rows[0].length;
  const h = rows.length;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < w; ) {
      const ch = row[x];
      let n = 1;
      while (x + n < w && row[x + n] === ch) n++;
      if (COLORS[ch]) rects += `<rect x='${x}' y='${y}' width='${n}' height='1' fill='${COLORS[ch].replace('#', '%23')}'/>`;
      x += n;
    }
  });
  return `url("data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' width='${w}' height='${h}' viewBox='0 0 ${w} ${h}' shape-rendering='crispEdges'>${rects}</svg>")`;
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const path = join(root, 'styles.css');
const css = readFileSync(path, 'utf8');
const begin = '/* frames:begin (generated by tools/frames.mjs) */';
const end = '/* frames:end */';
const block = `${begin}\n${Object.entries(FRAMES).map(([name, rows]) => `  --${name}: ${svg(rows)};`).join('\n')}\n  ${end}`;
const a = css.indexOf(begin);
const b = css.indexOf(end);
if (a < 0 || b < 0) throw new Error('styles.css has no frames:begin/frames:end block');
writeFileSync(path, css.slice(0, a) + block + css.slice(b + end.length));
console.log(`wrote ${Object.keys(FRAMES).length} frames`);
